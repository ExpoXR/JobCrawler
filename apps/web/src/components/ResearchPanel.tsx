'use client';

import { useCallback, useState } from 'react';

/**
 * "Research this" trigger (plan section 21).
 *
 * Deliberately on-demand: research may call a paid provider, so it runs when
 * the user asks for it rather than for every result in a list.
 *
 * With no AI provider configured the endpoint still answers, using the
 * rule-based explanation derived from the scoring evidence.
 */

interface ResearchResponse {
  research: {
    summary: string;
    strengths: string[];
    concerns: string[];
    sources: Array<{ url: string; provider: string }>;
    provider: string;
    model: string;
    generated: boolean;
    cachedAt?: string;
  };
  score: number;
  cached: boolean;
}

export interface ResearchPanelProps {
  jobId?: string;
  companyId?: string;
}

export function ResearchPanel({ jobId, companyId }: ResearchPanelProps) {
  const [result, setResult] = useState<ResearchResponse | undefined>();
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | undefined>();

  const run = useCallback(
    async (refresh: boolean) => {
      setBusy(true);
      setError(undefined);
      try {
        const response = await fetch('/api/research', {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({
            ...(jobId ? { jobId } : {}),
            ...(companyId ? { companyId } : {}),
            refresh,
          }),
        });

        if (!response.ok) {
          const payload = (await response.json().catch(() => ({}))) as { error?: string };
          setError(payload.error ?? 'Analysis failed.');
          return;
        }

        setResult((await response.json()) as ResearchResponse);
      } catch {
        setError('Could not reach the server.');
      } finally {
        setBusy(false);
      }
    },
    [jobId, companyId],
  );

  return (
    <section className="panel" style={{ marginBottom: '1rem' }}>
      <h2>Analysis</h2>

      {!result ? (
        <>
          <p className="hint">
            Analyse how this result fits, with the sources behind each statement.
          </p>
          <button
            type="button"
            className="button full"
            onClick={() => void run(false)}
            disabled={busy}
          >
            {busy ? 'Analysing…' : 'Research this'}
          </button>
        </>
      ) : (
        <>
          <p style={{ whiteSpace: 'pre-wrap' }}>{result.research.summary}</p>

          {result.research.strengths.length > 0 ? (
            <>
              <h3>Strengths</h3>
              <ul className="evidence-list" style={{ flexDirection: 'column', gap: '0.2rem' }}>
                {result.research.strengths.map((entry) => (
                  <li className="match" key={entry}>
                    <span className="marker" aria-hidden="true">
                      ✓
                    </span>
                    <span>{entry}</span>
                  </li>
                ))}
              </ul>
            </>
          ) : null}

          {result.research.concerns.length > 0 ? (
            <>
              <h3>Concerns</h3>
              <ul className="evidence-list" style={{ flexDirection: 'column', gap: '0.2rem' }}>
                {result.research.concerns.map((entry) => (
                  <li className="partial" key={entry}>
                    <span className="marker" aria-hidden="true">
                      △
                    </span>
                    <span>{entry}</span>
                  </li>
                ))}
              </ul>
            </>
          ) : null}

          {result.research.sources.length > 0 ? (
            <>
              <h3>Sources</h3>
              <ul className="source-list">
                {result.research.sources.map((source) => (
                  <li key={source.url}>
                    <a href={source.url} target="_blank" rel="noopener noreferrer nofollow">
                      {source.url}
                    </a>
                  </li>
                ))}
              </ul>
            </>
          ) : null}

          <p className="hint" style={{ marginTop: '0.6rem' }}>
            {result.research.generated
              ? `Generated by ${result.research.provider}${
                  result.research.model ? ` (${result.research.model})` : ''
                }. Verify against the sources above.`
              : 'Derived from the scoring evidence — no AI provider is configured.'}
            {result.cached ? ' Cached result.' : ''}
          </p>

          <button
            type="button"
            className="button secondary"
            onClick={() => void run(true)}
            disabled={busy}
          >
            {busy ? 'Re-running…' : 'Re-run analysis'}
          </button>
        </>
      )}

      {error ? (
        <p className="notice error" role="alert" style={{ marginTop: '0.6rem' }}>
          {error}
        </p>
      ) : null}
    </section>
  );
}
